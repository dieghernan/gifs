# Generate citations and release metadata from CITATION.cff.
require "yaml"
require "date"
require "json"

root = File.expand_path("..", __dir__)
cff = YAML.safe_load_file(File.join(root, "CITATION.cff"), permitted_classes: [Date])
citation = cff.fetch("preferred-citation")
metadata = JSON.parse(File.read(File.join(root, "_data/structured_data.json"), encoding: "UTF-8"))
%w[version doi authors].each do |field|
  abort "CITATION.cff has inconsistent #{field}" unless cff[field] == citation[field]
end
names = citation.fetch("authors").map do |author|
  initials = author.fetch("given-names").split.map { |name| "#{name[0]}." }.join(" ")
  "#{author.fetch('family-names')}, #{initials}"
end.join("; ")
bib_authors = citation.fetch("authors").map do |author|
  "#{author.fetch('family-names')}, #{author.fetch('given-names')}"
end.join(" and ")
doi_url = citation["doi"] && "https://doi.org/#{citation['doi']}"
release_url = "#{cff.fetch('repository-code')}/releases/tag/v#{citation.fetch('version')}"
citation_url = doi_url || release_url
concept_url = "https://doi.org/#{metadata.fetch('archive').fetch('conceptDoi')}"
text = "#{names} (#{citation.fetch('year')}). #{citation.fetch('title')} (Version #{citation.fetch('version')}) [Data set]. #{citation_url}"
bibtex = <<~BIBTEX
  @misc{hernangomez_grandes_incendios,
    author = {#{bib_authors}},
    title = {#{citation.fetch('title')}},
    year = {#{citation.fetch('year')}},
    version = {#{citation.fetch('version')}},
  #{citation['doi'] ? "  doi = {#{citation['doi']}},\n" : ""}  url = {#{citation_url}},
    note = {Data set}
  }
BIBTEX
release = {
  "version" => citation.fetch("version"),
  "dateReleased" => cff.fetch("date-released").to_s,
  "doi" => citation["doi"],
  "doiUrl" => doi_url,
  "conceptDoiUrl" => concept_url,
  "releaseUrl" => release_url,
  "citeAs" => text,
  "bibtex" => bibtex
}
block = <<~MARKDOWN
  <!-- citation:start; generated by scripts/citation.rb -->
  ## Cómo citar

  > #{names} (#{citation.fetch('year')}). *#{citation.fetch('title')}*
  > (Version #{citation.fetch('version')}) [Data set].
  > #{citation_url}

  <details markdown="1">
  <summary>Referencia en BibTeX</summary>

  ```bibtex
  #{bibtex.rstrip}
  ```

  </details>

  El [DOI general](#{concept_url}) reúne las versiones del proyecto.
  Para identificar los datos utilizados en un análisis, cite el DOI de la
  versión correspondiente.
  <!-- citation:end -->
MARKDOWN

outputs = { "_data/citation.json" => JSON.pretty_generate(release) + "\n" }
%w[README.md index.md].each do |file|
  original = File.read(File.join(root, file), encoding: "UTF-8").gsub("\r\n", "\n")
  pattern = if original.include?("<!-- citation:start;")
    /<!-- citation:start;.*?<!-- citation:end -->\n*/m
  else
    /## Cómo citar\n.*?(?=## Referencias)/m
  end
  abort "Missing citation section in #{file}" unless original.match?(pattern)
  outputs[file] = original.sub(pattern, block + "\n")
end
outputs.each do |file, output|
  path = File.join(root, file)
  if ARGV.include?("--check")
    current = File.exist?(path) && File.read(path, encoding: "UTF-8").gsub("\r\n", "\n")
    abort "Stale citation in #{file}. Run ruby scripts/citation.rb" unless current == output
  else
    File.write(path, output, encoding: "UTF-8")
  end
end
